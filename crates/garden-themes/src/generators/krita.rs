//! Krita colour-scheme generator.
//!
//! Produces `krita/Garden.colors` — a KDE colour scheme, the format
//! Krita uses for its window themes. Link it into
//! `~/.local/share/krita/color-schemes/` and choose "Garden" once
//! under Settings → Themes; from then on Krita shows the active
//! palette each time it starts.
//!
//! The scheme is always named "Garden", so switching palette changes
//! the file's colours without changing which theme Krita has selected.
//!
//! # Color mapping
//!
//! | Scheme entry            | Palette role                         |
//! |-------------------------|--------------------------------------|
//! | window, button, tooltip | `base`, `base-raised`, `base-raised` |
//! | views                   | `base-deep` (dark) or `base-raised`  |
//! | alternate rows          | `base`                               |
//! | text                    | `text-1`; inactive `text-3`          |
//! | selection, focus, links | `accent`                             |
//! | negative / positive     | `urgent` / `ok`                      |
//! | neutral                 | `accent`                             |

use garden_core::{ColorRole, HexColor, Palette};

use super::ThemeGenerator;

/// Krita colour-scheme generator.
pub struct Krita;

/// Formats a colour as the `r,g,b` triplet KDE colour schemes use.
fn rgb(color: &HexColor) -> String {
    format!("{},{},{}", color.r(), color.g(), color.b())
}

impl ThemeGenerator for Krita {
    fn name(&self) -> &str {
        "krita"
    }

    fn relative_path(&self) -> &str {
        "krita/Garden.colors"
    }

    fn generate(&self, palette: &Palette) -> String {
        let c = |role: ColorRole| -> &HexColor {
            palette
                .color(role)
                .expect("palette should be validated before generation")
        };

        let base = c(ColorRole::Base);
        let deep = c(ColorRole::BaseDeep);
        let raised = c(ColorRole::BaseRaised);
        let text1 = c(ColorRole::Text1);
        let text3 = c(ColorRole::Text3);
        let accent = c(ColorRole::Accent);
        let urgent = c(ColorRole::Urgent);
        let ok = c(ColorRole::Ok);

        let view = if palette.is_dark() { deep } else { raised };
        let on_accent = if accent.contrast(deep) >= accent.contrast(text1) {
            deep
        } else {
            text1
        };

        // One `[Colors:…]` group: a background, its alternate, and the
        // text drawn on it.
        let group = |name: &str, bg: &HexColor, alt: &HexColor, fg: &HexColor, dim: &HexColor| {
            format!(
                "\
[Colors:{name}]
BackgroundAlternate={alt}
BackgroundNormal={bg}
DecorationFocus={accent}
DecorationHover={accent}
ForegroundActive={accent}
ForegroundInactive={dim}
ForegroundLink={accent}
ForegroundNegative={urgent}
ForegroundNeutral={accent}
ForegroundNormal={fg}
ForegroundPositive={ok}
ForegroundVisited={dim}

",
                alt = rgb(alt),
                bg = rgb(bg),
                fg = rgb(fg),
                dim = rgb(dim),
                accent = rgb(accent),
                urgent = rgb(urgent),
                ok = rgb(ok),
            )
        };

        let mut out = format!(
            "\
# Garden theme — {name} {icon}
# Generated by garden-themes. Do not edit by hand.

[ColorEffects:Disabled]
Color={base}
ColorAmount=0
ColorEffect=0
ContrastAmount=0.65
ContrastEffect=1
IntensityAmount=0.1
IntensityEffect=2

[ColorEffects:Inactive]
ChangeSelectionColor=false
Color={base}
ColorAmount=0
ColorEffect=0
ContrastAmount=0
ContrastEffect=0
Enable=false
IntensityAmount=0
IntensityEffect=0

",
            name = palette.name,
            icon = palette.icon,
            base = rgb(base),
        );

        out.push_str(&group("Button", raised, base, text1, text3));
        out.push_str(&group("Selection", accent, accent, on_accent, on_accent));
        out.push_str(&group("Tooltip", raised, base, text1, text3));
        out.push_str(&group("View", view, base, text1, text3));
        out.push_str(&group("Window", base, raised, text1, text3));
        out.push_str(&group("Complementary", deep, base, text1, text3));

        out.push_str(&format!(
            "\
[General]
ColorScheme=Garden
Name=Garden

[WM]
activeBackground={bar}
activeForeground={fg}
inactiveBackground={base}
inactiveForeground={dim}
",
            bar = rgb(raised),
            fg = rgb(text1),
            base = rgb(base),
            dim = rgb(text3),
        ));
        out
    }
}
