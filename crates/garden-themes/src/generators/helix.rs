impl ThemeGenerator for Helix {
    fn name(&self) -> &str {
        "helix"
    }

    fn relative_path(&self) -> &str {
        "helix/garden.toml"
    }

    fn generate(&self, palette: &Palette) -> String {
        // Helper: look up a role and return its `#rrggbb` value.
        let c = |role: ColorRole| -> &str {
            palette
                .color(role)
                .expect("palette should be validated before generation")
                .as_str()
        };

        format!(
            "\
# Garden theme — {name} {icon}
# Generated by garden-themes. Do not edit by hand.

{SCOPES}
[palette]
base-deep = \"{base_deep}\"
base = \"{base}\"
base-raised = \"{base_raised}\"
base-hl = \"{base_hl}\"
border-sub = \"{border_sub}\"
border = \"{border}\"
text-4 = \"{text4}\"
text-3 = \"{text3}\"
text-2 = \"{text2}\"
text-1 = \"{text1}\"
accent = \"{accent}\"
urgent = \"{urgent}\"
ok = \"{ok}\"
",
            name = palette.name,
            icon = palette.icon,
            base_deep = c(ColorRole::BaseDeep),
            base = c(ColorRole::Base),
            base_raised = c(ColorRole::BaseRaised),
            base_hl = c(ColorRole::BaseHl),
            border_sub = c(ColorRole::BorderSub),
            border = c(ColorRole::Border),
            text4 = c(ColorRole::Text4),
            text3 = c(ColorRole::Text3),
            text2 = c(ColorRole::Text2),
            text1 = c(ColorRole::Text1),
            accent = c(ColorRole::Accent),
            urgent = c(ColorRole::Urgent),
            ok = c(ColorRole::Ok),
        )
    }
}
