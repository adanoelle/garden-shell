//! Helix editor theme generator.
//!
//! Produces a `helix/garden.toml` Helix theme. The 13 semantic roles
//! are emitted once in the theme's `[palette]` table under their
//! Garden names (`base`, `text-2`, `accent`, …) and every scope refers
//! to them by name, so the file reads as the role mapping itself.
//!
//! The mapping follows the [kakoune](super::kakoune) generator: text
//! roles carry the syntax hierarchy (`text-1` names, `text-2` types,
//! `text-3` keywords and operators, `text-4` comments) and the three
//! semantic colors are used sparingly (`ok` strings, `accent` values,
//! `urgent` errors).
//!
//! Link the file into Helix's theme directory as
//! `~/.config/helix/themes/garden.toml` and set `theme = "garden"`;
//! running editors reload it on SIGUSR1.

use garden_core::{ColorRole, Palette};

use super::ThemeGenerator;

/// Helix theme generator.
///
/// Generates a complete Helix theme file (UI, diagnostics, syntax,
/// markup, and diff scopes).
pub struct Helix;

