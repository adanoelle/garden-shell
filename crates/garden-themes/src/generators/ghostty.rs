//! Ghostty terminal emulator theme generator.
//!
//! Produces a `ghostty/garden-theme` file that maps Garden's 13
//! semantic color roles to Ghostty's color settings: background,
//! foreground, cursor, selection, and the 16 ANSI palette slots. The
//! ANSI mapping is the same as the [kitty](super::kitty) generator's,
//! so both terminals render programs identically.
//!
//! The file is a Ghostty config fragment. Include it from the main
//! config with `config-file = ?~/.config/garden/themes/ghostty/garden-theme`
//! (the `?` makes it optional) and do not set `theme`; running
//! instances pick up changes on SIGUSR2.

use garden_core::{ColorRole, Palette};

use super::ThemeGenerator;

/// Ghostty theme generator.
///
/// Generates a Ghostty config fragment suitable for inclusion via
/// `config-file` in the main Ghostty config.
pub struct Ghostty;

impl ThemeGenerator for Ghostty {
    fn name(&self) -> &str {
        "ghostty"
    }

    fn relative_path(&self) -> &str {
        "ghostty/garden-theme"
    }

    fn generate(&self, palette: &Palette) -> String {
        // Helper: look up a role and return its `#rrggbb` value.
        let c = |role: ColorRole| -> &str {
            palette
                .color(role)
                .expect("palette should be validated before generation")
                .as_str()
        };

        format!(
            "\
# Garden theme — {name} {icon}
# Generated by garden-themes. Do not edit by hand.

# Special colors
background = {base}
foreground = {text1}
cursor-color = {text1}
cursor-text = {base}
selection-background = {base_hl}
selection-foreground = {text1}

# Normal colors (0–7)
palette = 0={base_deep}
palette = 1={urgent}
palette = 2={ok}
palette = 3={accent}
palette = 4={text3}
palette = 5={border}
palette = 6={text2}
palette = 7={text2}

# Bright colors (8–15)
palette = 8={border}
palette = 9={urgent}
palette = 10={ok}
palette = 11={accent}
palette = 12={text2}
palette = 13={text3}
palette = 14={text1}
palette = 15={text1}
",
            name = palette.name,
            icon = palette.icon,
            base = c(ColorRole::Base),
            base_deep = c(ColorRole::BaseDeep),
            base_hl = c(ColorRole::BaseHl),
            border = c(ColorRole::Border),
            text1 = c(ColorRole::Text1),
            text2 = c(ColorRole::Text2),
            text3 = c(ColorRole::Text3),
            accent = c(ColorRole::Accent),
            urgent = c(ColorRole::Urgent),
            ok = c(ColorRole::Ok),
        )
    }
}
