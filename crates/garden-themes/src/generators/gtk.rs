//! GTK named-colour generator.
//!
//! Produces `gtk/garden-colors.css` — a list of `@define-color` lines
//! that recolour GTK 3 and GTK 4 applications. Import it from
//! `~/.config/gtk-3.0/gtk.css` and `~/.config/gtk-4.0/gtk.css`:
//!
//! ```css
//! @import url("file:///home/you/.config/garden/themes/gtk/garden-colors.css");
//! ```
//!
//! The names are libadwaita's, so GTK 4 applications follow them
//! directly. GTK 3 applications follow them under the `adw-gtk3`
//! theme, which is written against the same names; the older GTK 3
//! names (`theme_bg_color` and the like) are defined too for widgets
//! that still use them.
//!
//! Applications read the file when they start. `garden-themes apply`
//! also sets the desktop's dark or light preference to match the
//! palette (see [`Palette::is_dark`]).
//!
//! # Color mapping
//!
//! | GTK colour                 | Dark palette  | Light palette |
//! |----------------------------|---------------|---------------|
//! | window background          | `base`        | `base`        |
//! | views (lists, text areas)  | `base-deep`   | `base-raised` |
//! | header bar, sidebar        | `base-raised` | `base-deep`   |
//! | cards, popovers, dialogs   | `base-raised` | `base-raised` |
//! | text                       | `text-1`      | `text-1`      |
//! | accent, selection          | `accent`      | `accent`      |
//! | destructive, error         | `urgent`      | `urgent`      |
//! | success                    | `ok`          | `ok`          |
//! | warning                    | `accent`      | `accent`      |
//! | borders                    | `border`      | `border`      |
//!
//! Text drawn on an accent, urgent or ok background is whichever of
//! `base-deep` and `text-1` contrasts with it more.

use garden_core::{ColorRole, HexColor, Palette};

use super::ThemeGenerator;

/// GTK named-colour generator.
pub struct Gtk;

/// Returns whichever of the two candidates contrasts more with `bg`.
fn on<'a>(bg: &HexColor, a: &'a HexColor, b: &'a HexColor) -> &'a HexColor {
    if bg.contrast(a) >= bg.contrast(b) {
        a
    } else {
        b
    }
}

impl ThemeGenerator for Gtk {
    fn name(&self) -> &str {
        "gtk"
    }

    fn relative_path(&self) -> &str {
        "gtk/garden-colors.css"
    }

    fn generate(&self, palette: &Palette) -> String {
        let c = |role: ColorRole| -> &HexColor {
            palette
                .color(role)
                .expect("palette should be validated before generation")
        };

        let dark = palette.is_dark();
        let base = c(ColorRole::Base);
        let deep = c(ColorRole::BaseDeep);
        let raised = c(ColorRole::BaseRaised);
        let text1 = c(ColorRole::Text1);
        let text3 = c(ColorRole::Text3);
        let border = c(ColorRole::Border);
        let accent = c(ColorRole::Accent);
        let urgent = c(ColorRole::Urgent);
        let ok = c(ColorRole::Ok);

        // Views sit below the window in a dark palette and above it in
        // a light one; bars do the opposite. This is libadwaita's own
        // arrangement.
        let (view, bar) = if dark { (deep, raised) } else { (raised, deep) };

        let mut out = format!(
            "\
/* Garden theme — {name} {icon} ({mode})
 * Generated by garden-themes. Do not edit by hand. */

",
            name = palette.name,
            icon = palette.icon,
            mode = if dark { "dark" } else { "light" },
        );

        let colors: &[(&str, &HexColor)] = &[
            // libadwaita (GTK 4, and GTK 3 under adw-gtk3)
            ("window_bg_color", base),
            ("window_fg_color", text1),
            ("view_bg_color", view),
            ("view_fg_color", text1),
            ("headerbar_bg_color", bar),
            ("headerbar_fg_color", text1),
            ("headerbar_border_color", text1),
            ("headerbar_backdrop_color", base),
            ("sidebar_bg_color", bar),
            ("sidebar_fg_color", text1),
            ("sidebar_backdrop_color", base),
            ("sidebar_border_color", border),
            ("secondary_sidebar_bg_color", base),
            ("secondary_sidebar_fg_color", text1),
            ("secondary_sidebar_backdrop_color", base),
            ("secondary_sidebar_border_color", border),
            ("card_bg_color", raised),
            ("card_fg_color", text1),
            ("dialog_bg_color", raised),
            ("dialog_fg_color", text1),
            ("popover_bg_color", raised),
            ("popover_fg_color", text1),
            ("thumbnail_bg_color", raised),
            ("thumbnail_fg_color", text1),
            ("accent_color", accent),
            ("accent_bg_color", accent),
            ("accent_fg_color", on(accent, deep, text1)),
            ("destructive_color", urgent),
            ("destructive_bg_color", urgent),
            ("destructive_fg_color", on(urgent, deep, text1)),
            ("error_color", urgent),
            ("error_bg_color", urgent),
            ("error_fg_color", on(urgent, deep, text1)),
            ("success_color", ok),
            ("success_bg_color", ok),
            ("success_fg_color", on(ok, deep, text1)),
            ("warning_color", accent),
            ("warning_bg_color", accent),
            ("warning_fg_color", on(accent, deep, text1)),
            // GTK 3's older names
            ("theme_bg_color", base),
            ("theme_fg_color", text1),
            ("theme_base_color", view),
            ("theme_text_color", text1),
            ("theme_selected_bg_color", accent),
            ("theme_selected_fg_color", on(accent, deep, text1)),
            ("insensitive_bg_color", base),
            ("insensitive_fg_color", text3),
            ("insensitive_base_color", base),
            ("theme_unfocused_bg_color", base),
            ("theme_unfocused_fg_color", text1),
            ("theme_unfocused_base_color", view),
            ("theme_unfocused_text_color", text1),
            ("theme_unfocused_selected_bg_color", accent),
            ("theme_unfocused_selected_fg_color", on(accent, deep, text1)),
            ("unfocused_insensitive_color", text3),
            ("borders", border),
            ("unfocused_borders", border),
            ("link_color", accent),
        ];

        for (name, color) in colors {
            out.push_str(&format!("@define-color {name} {color};\n"));
        }
        out
    }
}
